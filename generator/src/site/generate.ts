/**
 * `bun run site:generate`: translates the site's upstream sources
 * (`upstream/site/`) into `site/generated/` (docs/adr/0034):
 *
 * - `examples/<name>.tsx`: the examples of the docs pages, with hand-written
 *   overrides (`site/examples/overrides/`) for functions that need React.
 * - `home/<card>.tsx`: the cards of the home page.
 * - `docs/<component>.mdx`: the component pages.
 * - `icons.tsx`: the icons the examples import from `@/components/icons`.
 * - `manifest.json`: which page each example belongs to.
 */
import { existsSync, readdirSync, readFileSync, rmSync } from "node:fs"
import path from "node:path"
import { OVERRIDES, SKIPPED } from "../../../site/examples/overrides"
import { formatWithBiome } from "../emit/format"
import { ROOT } from "../paths"
import { previewNames, SiteSourcesStore } from "../upstream/site-sources"
import { type DocsContext, transformDocs } from "./docs"
import { buildIconsModule, type IconUse } from "./icons-module"
import {
  applyOverride,
  type FunctionIssue,
  tidyImports,
  translateExample,
} from "./translate"

export const SITE_DIR = path.join(ROOT, "site")
export const GENERATED_DIR = path.join(SITE_DIR, "generated")
const OVERRIDES_DIR = path.join(SITE_DIR, "examples", "overrides")

export interface ExampleEntry {
  /** The component page that previews it. */
  component: string
  /** Why the site has no version of it, when it has none. */
  skipped?: string
}

export interface SiteManifest {
  commit: string
  examples: Record<string, ExampleEntry>
}

export interface MissingOverride extends FunctionIssue {
  example: string
}

export interface SiteOutput {
  /** Path relative to `site/generated/` → content. */
  files: Map<string, string>
  missing: MissingOverride[]
  /** Overrides whose upstream function changed (sha256 mismatch) or vanished. */
  stale: string[]
}

const LICENSE =
  "// Derived from shadcn/ui. Copyright (c) 2023 shadcn. MIT License."

function header(source: string, commit: string, notes: string[] = []): string {
  return [
    `// Generated by \`bun run site:generate\` from shadcn/ui ${source} (shadcn-ui/ui@${commit.slice(0, 12)}); do not edit.`,
    ...notes.map((note) => `// ${note}`),
    LICENSE,
  ].join("\n")
}

function format(text: string, file: string): string {
  return formatWithBiome(text, path.join("site/generated", file))
}

interface Translation {
  text: string
  icons: IconUse[]
}

function translate(
  name: string,
  source: string,
  output: SiteOutput
): Translation | null {
  const result = translateExample(name, source)
  const override = OVERRIDES[name]
  let text = result.text
  if (override) {
    for (const [fn, sha256] of Object.entries(override.functions)) {
      const upstream = result.hashes.get(fn)
      if (!upstream) {
        output.stale.push(`${name}#${fn}: the upstream function is gone`)
      } else if (upstream !== sha256) {
        output.stale.push(
          `${name}#${fn}: upstream changed (now sha256 ${upstream}); review the override`
        )
      }
    }
    const file = path.join(OVERRIDES_DIR, `${name}.tsx`)
    if (!existsSync(file)) throw new Error(`missing override file ${file}`)
    text = applyOverride(
      text,
      readFileSync(file, "utf8"),
      Object.keys(override.functions)
    )
  }
  const uncovered = result.issues.filter(
    (issue) => !override?.functions[issue.name]
  )
  if (uncovered.length > 0) {
    output.missing.push(
      ...uncovered.map((issue) => ({ ...issue, example: name }))
    )
    return null
  }
  return {
    text: tidyImports(text),
    icons: result.icons.map((icon) => ({
      name: icon.name,
      source: icon.source,
    })),
  }
}

export function generateSite(): SiteOutput {
  const store = new SiteSourcesStore(ROOT)
  const lock = store.readLock()
  if (!lock)
    throw new Error(
      "upstream/site/lock.json is missing; run `bun run upstream:sync`."
    )
  const output: SiteOutput = { files: new Map(), missing: [], stale: [] }
  const icons: IconUse[] = []
  const manifest: SiteManifest = { commit: lock.commit, examples: {} }

  const components = store.list("docs", ".mdx")
  const context: DocsContext = {
    components: new Set(components),
    pages: new Set(
      readdirSync(path.join(SITE_DIR, "content", "docs")).map((file) =>
        file.replace(/\.mdx$/, "")
      )
    ),
  }

  for (const component of components) {
    const mdx = store.read(`docs/${component}.mdx`)
    const docs = transformDocs(component, mdx, context)
    output.files.set(`docs/${component}.mdx`, docs.text)
    icons.push(...docs.icons)
    for (const name of previewNames(mdx)) {
      if (manifest.examples[name]) continue
      const skipped = SKIPPED[name]
      if (skipped) {
        manifest.examples[name] = { component, skipped }
        continue
      }
      const source = store.readOptional(`examples/${name}.tsx`)
      if (source === null) {
        manifest.examples[name] = {
          component,
          skipped: "The example is not in the upstream snapshot.",
        }
        continue
      }
      manifest.examples[name] = { component }
      const translation = translate(name, source, output)
      if (!translation) continue
      icons.push(...translation.icons)
      const overridden = OVERRIDES[name]
      output.files.set(
        `examples/${name}.tsx`,
        format(
          `${header(`apps/v4/examples/base/${name}.tsx`, lock.commit, overridden ? [`Overridden: ${Object.keys(overridden.functions).join(", ")} (site/examples/overrides/${name}.tsx).`] : [])}\n\n${translation.text}`,
          `examples/${name}.tsx`
        )
      )
    }
  }

  for (const card of store.list("home", ".tsx")) {
    if (card === "index") continue
    const translation = translate(
      `home/${card}`,
      store.read(`home/${card}.tsx`),
      output
    )
    if (!translation) continue
    icons.push(...translation.icons)
    output.files.set(
      `home/${card}.tsx`,
      format(
        `${header(`apps/v4/app/(app)/(root)/cards/${card}.tsx`, lock.commit)}\n\n${translation.text}`,
        `home/${card}.tsx`
      )
    )
  }

  output.files.set(
    "icons.tsx",
    format(
      buildIconsModule(
        icons,
        "// Generated by `bun run site:generate`: the icons the site's examples import; do not edit.\n// Lucide (ISC License), Tabler Icons (MIT License) and Hugeicons (MIT License) as their React packages render them."
      ),
      "icons.tsx"
    )
  )
  output.files.set("manifest.json", `${JSON.stringify(manifest, null, 2)}\n`)
  return output
}

/** Files under `site/generated/` that `output` does not produce. */
export function staleFiles(output: SiteOutput): string[] {
  const walk = (dir: string): string[] =>
    existsSync(dir)
      ? readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
          const full = path.join(dir, entry.name)
          return entry.isDirectory()
            ? walk(full)
            : [path.relative(GENERATED_DIR, full)]
        })
      : []
  return walk(GENERATED_DIR).filter((file) => !output.files.has(file))
}

export function removeFiles(files: string[]): void {
  for (const file of files) rmSync(path.join(GENERATED_DIR, file))
}
